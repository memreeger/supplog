-- Bildirim kutusu (çanın kaynağı). Metin değil type + params saklanır; istemci kendi dilinde çizer.
CREATE TABLE public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id bigint NOT NULL,
    type varchar(32) NOT NULL,
    -- Aynı olayın tekrarını önler (örn. exec:123:REMINDER). Alıcıyla birlikte benzersizdir.
    dedupe_key varchar(100) NOT NULL,
    execution_id bigint,
    routine_id bigint,
    actor_user_id bigint,
    -- Nudge tablosu V13'te gelir; FK'si orada eklenecek.
    nudge_id bigint,
    params jsonb NOT NULL DEFAULT '{}'::jsonb,
    read_at timestamp(6) with time zone,
    resolved_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_notifications_recipient_dedupe UNIQUE (recipient_user_id, dedupe_key),
    CONSTRAINT fk_notifications_recipient
        FOREIGN KEY (recipient_user_id) REFERENCES public.users(id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_execution
        FOREIGN KEY (execution_id) REFERENCES public.routine_executions(id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_routine
        FOREIGN KEY (routine_id) REFERENCES public.routines(id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_actor
        FOREIGN KEY (actor_user_id) REFERENCES public.users(id) ON DELETE SET NULL
);

-- Çanın listesi: alıcının son bildirimleri.
CREATE INDEX idx_notifications_recipient_created
    ON public.notifications (recipient_user_id, created_at DESC);

-- Okunmamış sayısı: sadece açık (çözülmemiş) ve okunmamış satırlar.
CREATE INDEX idx_notifications_recipient_unread
    ON public.notifications (recipient_user_id)
    WHERE read_at IS NULL AND resolved_at IS NULL;

CREATE INDEX idx_notifications_execution
    ON public.notifications (execution_id);

-- Kullanıcının bildirim tercihleri. Satır yoksa varsayılanlar geçerlidir (hepsi açık).
CREATE TABLE public.notification_preferences (
    user_id bigint PRIMARY KEY,
    push_enabled boolean NOT NULL DEFAULT true,
    reminders_enabled boolean NOT NULL DEFAULT true,
    supporter_alerts_enabled boolean NOT NULL DEFAULT true,
    nudges_enabled boolean NOT NULL DEFAULT true,
    hide_details_in_push boolean NOT NULL DEFAULT false,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT fk_notification_preferences_user
        FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE
);
