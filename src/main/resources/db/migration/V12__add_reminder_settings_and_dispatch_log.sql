-- Rutin başına hatırlatma ayarı. Satır yoksa varsayılan geçerlidir (açık, 30 dk önce).
CREATE TABLE public.routine_reminder_settings (
    routine_id bigint PRIMARY KEY,
    enabled boolean NOT NULL DEFAULT true,
    lead_minutes integer NOT NULL DEFAULT 30,
    created_at timestamp(6) with time zone NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT ck_routine_reminder_settings_lead CHECK (lead_minutes IN (10, 20, 30, 60)),
    CONSTRAINT fk_routine_reminder_settings_routine
        FOREIGN KEY (routine_id) REFERENCES public.routines(id) ON DELETE CASCADE
);

-- "Bu dilimi bu kişiye zaten gönderdim mi?" kaydı. Zamanlayıcı yeniden başlasa ya da iki instance
-- çalışsa bile aynı dilim iki kez gönderilmez: INSERT ... ON CONFLICT DO NOTHING.
CREATE TABLE public.notification_dispatch_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id bigint NOT NULL,
    recipient_user_id bigint NOT NULL,
    kind varchar(20) NOT NULL,
    slot varchar(20) NOT NULL,
    sent_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_notification_dispatch_log_slot
        UNIQUE (execution_id, recipient_user_id, kind, slot),
    CONSTRAINT fk_notification_dispatch_log_execution
        FOREIGN KEY (execution_id) REFERENCES public.routine_executions(id) ON DELETE CASCADE,
    CONSTRAINT fk_notification_dispatch_log_recipient
        FOREIGN KEY (recipient_user_id) REFERENCES public.users(id) ON DELETE CASCADE
);

CREATE INDEX idx_notification_dispatch_log_sent_at
    ON public.notification_dispatch_log (sent_at);
