-- Destekçiden sahibe giden dürtme mesajı. Ya hazır şablon anahtarı (template_key) ya serbest metin (message) vardır.
-- Hazır şablonların metni istemcide (i18n) durur; sunucu sadece anahtarı saklar.
CREATE TABLE public.nudges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_user_id bigint NOT NULL,
    recipient_user_id bigint NOT NULL,
    routine_id bigint NOT NULL,
    template_key varchar(40),
    message varchar(280),
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT ck_nudges_content CHECK ((template_key IS NOT NULL) <> (message IS NOT NULL)),
    CONSTRAINT fk_nudges_sender
        FOREIGN KEY (sender_user_id) REFERENCES public.users(id) ON DELETE CASCADE,
    CONSTRAINT fk_nudges_recipient
        FOREIGN KEY (recipient_user_id) REFERENCES public.users(id) ON DELETE CASCADE,
    CONSTRAINT fk_nudges_routine
        FOREIGN KEY (routine_id) REFERENCES public.routines(id) ON DELETE CASCADE
);

-- Hız sınırı sorguları: gönderen + rutin, gönderen + alıcı.
CREATE INDEX idx_nudges_sender_routine_created
    ON public.nudges (sender_user_id, routine_id, created_at DESC);

CREATE INDEX idx_nudges_sender_recipient_created
    ON public.nudges (sender_user_id, recipient_user_id, created_at DESC);

-- Alıcının belirli bir destekçiyi sessize alması (taciz önleme). Gönderen sebebi görmez.
CREATE TABLE public.nudge_mutes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id bigint NOT NULL,
    sender_user_id bigint NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_nudge_mutes_pair UNIQUE (recipient_user_id, sender_user_id),
    CONSTRAINT fk_nudge_mutes_recipient
        FOREIGN KEY (recipient_user_id) REFERENCES public.users(id) ON DELETE CASCADE,
    CONSTRAINT fk_nudge_mutes_sender
        FOREIGN KEY (sender_user_id) REFERENCES public.users(id) ON DELETE CASCADE
);

