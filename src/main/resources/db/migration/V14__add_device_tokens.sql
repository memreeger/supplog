-- Push gönderilecek cihazlar. push_token: FCM kayıt token'ı (ileride Firebase Installation ID olabilir, bu yüzden
-- genel bir ad). Token başka kullanıcıya geçebilir (paylaşılan cihaz); benzersizlik token üzerindedir.
CREATE TABLE public.device_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    push_token varchar(512) NOT NULL,
    platform varchar(10) NOT NULL,
    locale varchar(10),
    app_version varchar(30),
    last_seen_at timestamp(6) with time zone NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_device_tokens_push_token UNIQUE (push_token),
    CONSTRAINT ck_device_tokens_platform CHECK (platform IN ('ANDROID', 'IOS', 'WEB')),
    CONSTRAINT fk_device_tokens_user
        FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE
);

CREATE INDEX idx_device_tokens_user ON public.device_tokens (user_id);

-- Bayat token temizliği (günlük iş) için.
CREATE INDEX idx_device_tokens_last_seen ON public.device_tokens (last_seen_at);
