CREATE TABLE public.role (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    name varchar(30),
    CONSTRAINT role_name_check CHECK (
        name IN ('ROLE_USER', 'ROLE_ADMIN')
    ),
    CONSTRAINT role_pkey PRIMARY KEY (id)
);


CREATE TABLE public.users (
