CREATE TABLE public.refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    token_hash varchar(64) NOT NULL,
    family_id uuid NOT NULL,
    token_version integer NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    family_expires_at timestamp(6) with time zone NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    last_used_at timestamp(6) with time zone,
    rotated_at timestamp(6) with time zone,
    replaced_by_id bigint,
    revoked_at timestamp(6) with time zone,
    revoke_reason varchar(30),
    device_name varchar(100),
    platform varchar(20) NOT NULL,
    ip_address varchar(45),
    user_agent varchar(255),
    CONSTRAINT uq_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id) REFERENCES public.users(id),
    CONSTRAINT fk_refresh_tokens_replaced_by
        FOREIGN KEY (replaced_by_id) REFERENCES public.refresh_tokens(id) ON DELETE SET NULL,
    CONSTRAINT ck_refresh_tokens_platform
        CHECK (platform IN ('ANDROID', 'IOS', 'WEB', 'UNKNOWN'))
);

CREATE INDEX idx_refresh_tokens_user_id
    ON public.refresh_tokens (user_id);

CREATE INDEX idx_refresh_tokens_family_id
    ON public.refresh_tokens (family_id);

CREATE INDEX idx_refresh_tokens_expires_at
    ON public.refresh_tokens (expires_at);
